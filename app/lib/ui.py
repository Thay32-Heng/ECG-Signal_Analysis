"""Shared sidebar controls, record selection and small UI helpers.

Keeping these here means the three pages stay focused on their own content and
every page behaves the same way when the user switches records or filters.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import streamlit as st

from lib import io as data_io
from lib.dsp import FilterSettings, SignalMetrics

UPLOAD_BYTES_KEY: str = "uploaded_bytes"
UPLOAD_NAME_KEY: str = "uploaded_name"
DEFAULT_LOW_HZ: float = 0.5
DEFAULT_HIGH_HZ: float = 40.0
DEFAULT_Q: float = 35.0

DISCLAIMER: str = (
    "**Synthetic demonstration signal.** The bundled record is generated by "
    "`data/create_data.py` from a P-QRS-T model — it is not a patient recording. "
    "Nothing in this app is a medical device, a diagnosis or clinical advice."
)


def _load_record() -> data_io.Record:
    """Return the active record, falling back to the bundled one.

    Returns:
        The record selected in the sidebar.
    """
    if UPLOAD_BYTES_KEY in st.session_state:
        raw: bytes = st.session_state[UPLOAD_BYTES_KEY]
        name: str = st.session_state.get(UPLOAD_NAME_KEY, "uploaded.csv")
        return data_io.load_upload(raw, name)
    return data_io.load_bundled()


def record_selector() -> data_io.Record:
    """Render the data-source controls in the sidebar and return the record.

    Returns:
        The active :class:`data_io.Record`.
    """
    with st.sidebar:
        st.subheader("Data source")
        upload = st.file_uploader(
            "Upload a CSV",
            type=["csv"],
            key="ecg_uploader",
            help="Columns `time` and `voltage`. `voltage_cleaned` is accepted as a fallback name.",
        )
        if upload is not None:
            st.session_state[UPLOAD_BYTES_KEY] = upload.getvalue()
            st.session_state[UPLOAD_NAME_KEY] = upload.name
        if UPLOAD_BYTES_KEY in st.session_state and st.button("Back to bundled record", width="stretch"):
            st.session_state.pop(UPLOAD_BYTES_KEY, None)
            st.session_state.pop(UPLOAD_NAME_KEY, None)
            # Dropping the stored bytes is not enough: the file_uploader keeps
            # its own value under this key and would re-store the file on the
            # next run, making the button a no-op.
            st.session_state.pop("ecg_uploader", None)
            st.rerun()

    try:
        record = _load_record()
    except data_io.DataValidationError as exc:
        st.error(f"Cannot use that file — {exc}")
        st.stop()
    except FileNotFoundError as exc:
        st.error(str(exc))
        st.stop()

    with st.sidebar:
        st.caption(
            f"**{record.name}**  \n"
            f"{record.time.size:,} samples · {record.fs:.0f} Hz · {record.duration_s:.1f} s"
        )
        if record.is_synthetic:
            st.caption(":violet[SYNTHETIC RECORD]")
        else:
            st.caption(":blue[USER UPLOAD]")
            if record.reference is None:
                st.caption("No reference column: SNR is unavailable, noise reduction is shown instead.")
    return record


def filter_controls(record: data_io.Record) -> FilterSettings:
    """Render the filter controls in the sidebar.

    Args:
        record: Active record, used to pre-fill the sampling rate.

    Returns:
        The chosen :class:`FilterSettings`.
    """
    with st.sidebar:
        st.divider()
        st.subheader("Filter chain")
        fs = st.number_input(
            "Sampling rate (Hz)",
            min_value=50.0,
            max_value=5000.0,
            # A CSV whose time column is in milliseconds (or in bare sample
            # indices) infers a rate below the widget floor, and Streamlit
            # raises rather than clamping. Clamp it here and say so.
            value=float(min(5000.0, max(50.0, round(record.fs)))),
            step=1.0,
            help=f"Detected from the time column: {record.fs:.1f} Hz. Change it only if you know better.",
        )
        nyquist = fs / 2.0
        notch_enabled = nyquist > 61.0
        mains = st.radio(
            "Powerline notch",
            options=("50 Hz", "60 Hz", "Off"),
            index=0 if notch_enabled else 2,
            horizontal=True,
            disabled=not notch_enabled,
            help="Removes the mains hum with a tapered FFT notch.",
        )
        if not notch_enabled:
            st.caption("The notch needs a sampling rate above 122 Hz.")
        use_bandpass = st.toggle("Butterworth band-pass", value=True)
        high_max = float(min(120.0, max(10.0, nyquist * 0.95)))
        low = st.slider(
            "Lower cutoff (Hz)",
            min_value=0.05,
            max_value=5.0,
            value=min(DEFAULT_LOW_HZ, 5.0),
            step=0.05,
            disabled=not use_bandpass,
            help="0.5 Hz is the standard monitoring-ECG high-pass: it removes baseline wander.",
        )
        high = st.slider(
            "Upper cutoff (Hz)",
            min_value=10.0,
            max_value=high_max,
            value=float(min(DEFAULT_HIGH_HZ, high_max)),
            step=1.0,
            disabled=not use_bandpass,
            help="40 Hz keeps the QRS and T wave while cutting muscle noise.",
        )
        with st.expander("Advanced"):
            q = st.slider(
                "Notch quality factor",
                min_value=10.0,
                max_value=80.0,
                value=DEFAULT_Q,
                step=5.0,
                help="Higher Q means a narrower notch. Width is at least ±1 Hz.",
            )

    return FilterSettings(
        fs=float(fs),
        notch_hz=None if (mains == "Off" or not notch_enabled) else float(mains.split()[0]),
        use_bandpass=bool(use_bandpass),
        low=float(low),
        high=float(high),
        q=float(q),
    )


def metric_cards(metrics: SignalMetrics, settings: FilterSettings) -> None:
    """Render the four headline metric cards.

    Args:
        metrics: Scored results for the current configuration.
        settings: Configuration being displayed.
    """
    snr_before = f"{metrics.snr_in_db:+.1f} dB" if metrics.has_reference else "no reference"
    snr_after = f"{metrics.snr_out_db:+.1f} dB" if metrics.has_reference else "no reference"
    snr_delta = f"{metrics.gain_db:+.1f} dB" if metrics.has_reference else None

    # Heart rate is shown once. Printing "BPM before 72.1 / BPM after 72.1"
    # looked like a bug even though it is a real finding (the detector survives
    # the noise), so the fourth card reports what filtering costs instead.
    bpm_out = f"{metrics.bpm_out:.1f}" if np.isfinite(metrics.bpm_out) else "n/a"
    bpm_delta = None
    if metrics.true_bpm is not None and np.isfinite(metrics.bpm_out):
        bpm_delta = f"{metrics.bpm_out - metrics.true_bpm:+.1f} vs true"

    peak_kept = (
        f"{100.0 * metrics.r_peak_ratio:.0f}%"
        if np.isfinite(metrics.r_peak_ratio)
        else "n/a"
    )

    left, mid_left, mid_right, right = st.columns(4)
    left.metric("SNR before", snr_before, help="Signal-to-noise ratio of the raw record against the clean reference.")
    mid_left.metric("SNR after", snr_after, delta=snr_delta, help="Higher is better; delta is the gain.")
    mid_right.metric(
        "Heart rate after filtering",
        bpm_out,
        delta=bpm_delta,
        help="Beats per minute recovered by the QRS detector on the filtered trace.",
    )
    right.metric(
        "R-peak height kept",
        peak_kept,
        help="How much of the true R-peak amplitude survives the filter chain. 100% means the filter removed noise and nothing else.",
    )
    st.caption(f"Active chain: {settings.label} · {metrics.n_beats_out} beats detected after filtering.")


def download_button(
    time: np.ndarray,
    filtered: np.ndarray,
    settings: FilterSettings,
    key: str,
) -> None:
    """Offer the filtered trace as a CSV download.

    Args:
        time: Sample times in seconds.
        filtered: Filtered signal.
        settings: Configuration used, embedded in the file name.
        key: Unique Streamlit widget key.
    """
    frame = pd.DataFrame({"time": time, "voltage_cleaned": filtered})
    st.download_button(
        "Download filtered CSV",
        data=frame.to_csv(index=False, float_format="%.6f"),
        file_name="ecg_filtered.csv",
        mime="text/csv",
        key=key,
        help=f"Columns: time, voltage_cleaned ({settings.label}).",
    )


def footer(record: data_io.Record) -> None:
    """Render the standing disclaimer at the bottom of a page.

    Args:
        record: Active record, used to decide which note to show.
    """
    st.divider()
    if record.is_synthetic:
        st.caption(DISCLAIMER)
    else:
        st.caption(
            "Uploaded record — metrics are only as good as the file. "
            "Nothing in this app is a medical device, a diagnosis or clinical advice."
        )
